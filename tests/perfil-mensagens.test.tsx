import {act,cleanup,render,screen} from "@testing-library/react";
import {afterEach,expect,it,vi} from "vitest";
import userEvent from "@testing-library/user-event";
import {MensagensPerfil} from "@/components/perfil/completo/MensagensPerfil";
import {PerfilProvider} from "@/components/PerfilProvider";
import {carregarMensagensPerfil,carregarSecaoPerfil} from "@/app/_actions/perfil-completo";
import {enviarMensagem} from "@/lib/mensagens";
vi.mock("@/app/_actions/perfil-completo",()=>({carregarMensagensPerfil:vi.fn(),carregarSecaoPerfil:vi.fn(),marcarMensagensPerfilLidas:vi.fn().mockResolvedValue({ok:true,dados:null})}));
vi.mock("@/lib/mensagens",()=>({enviarMensagem:vi.fn(),TAMANHO_MAXIMO:500}));
afterEach(cleanup);
it("não envia antes da carga inicial, evitando resposta antiga apagar mensagem confirmada",async()=>{
  let concluir!:(v:Awaited<ReturnType<typeof carregarMensagensPerfil>>)=>void;
  vi.mocked(carregarSecaoPerfil).mockResolvedValue({ok:true,dados:{itens:[{id:"chamado",criado_em:"2026-11-21",nome:"Lucas",status:"aceito"}],proxima:null}});
  vi.mocked(carregarMensagensPerfil).mockImplementation(()=>new Promise(resolve=>{concluir=resolve;}));
  render(<PerfilProvider perfil={{id:"dono",nome:"Ana",telefone:"81999990000",tipo:"ciclista",oficina:null,disponivel:false,criado_em:"2026-11-21"}}><MensagensPerfil/></PerfilProvider>);
  const user=userEvent.setup();
  await user.click(await screen.findByRole("button",{name:"Abrir conversa"}));
  await user.type(screen.getByRole("textbox",{name:"Mensagem"}),"Estou aqui");
  expect((screen.getByRole("button",{name:"Enviar mensagem"}) as HTMLButtonElement).disabled).toBe(true);
  expect(enviarMensagem).not.toHaveBeenCalled();
  await act(async()=>{concluir({ok:true,dados:{itens:[],proxima:null}});});
  expect((screen.getByRole("button",{name:"Enviar mensagem"}) as HTMLButtonElement).disabled).toBe(false);
});
